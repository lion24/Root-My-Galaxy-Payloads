#!/usr/bin/env python3
"""Compile a target header against stub measured values, to catch the mistakes that are not numbers.

A target header cannot be compiled before its firmware has been measured: `measured.h` is an `#error`
until then, by design. That leaves a gap in the middle - the header itself may have a typo, a macro
that is used but never defined, or an expression that does not parse - and the first time anybody
finds out is the CI run after the measurement, one step before a phone reboots into the wrong kernel.

So this compiles the header in its *unmeasured* form: the same `target.h`, byte for byte, next to a
`measured.h` and `p0_fingerprint.h` of stubs. What it answers is exactly the question the stubs can
answer - does the carried-over half of the header reference anything it does not define - and it also
checks the other direction, by diffing the macro names against a reference target header so a port
cannot silently lose one the chain needs.

It never writes into the tree. The header is copied to a temporary directory and compiled there, so a
check cannot leave a stub behind that a later build would pick up.

    tools/port/syntax_check.py --target dm2q-S916BXXUAGZIF --reference dm2q-S916BXXSAFZG1
    tools/port/syntax_check.py --self-test
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

TARGETS = Path(__file__).resolve().parents[2] / "src" / "targets"

# The macros a measured header supplies, which is also the list a stub has to define. Kept in the
# check rather than imported from `emit_target.py` so that a change in one is a visible change in
# both: what the emitter writes and what the header is allowed to assume are the same contract.
MEASURED = (
    "KIMAGE_TEXT_BASE",
    "P0_KERNEL_PHYS_LOAD",
    "BUILD_FINGERPRINT",
    "INIT_TASK_OFF",
    "PREPARE_KERNEL_CRED_OFF",
    "COMMIT_CREDS_OFF",
    "OVERRIDE_CREDS_OFF",
    "ROOT_TASK_GROUP_OFF",
    "SELINUX_ENFORCING_OFF",
    "KMALLOC_CACHES_OFF",
    "ANON_PIPE_BUF_OPS_OFF",
    "SYSTEM_UNBOUND_WQ_OFF",
    "CALL_USERMODEHELPER_EXEC_WORK_OFF",
    "ASHMEM_FOPS_OFF",
    "ASHMEM_MISC_FOPS_OFF",
    "ASHMEM_IOCTL_OFF",
    "ASHMEM_COMPAT_IOCTL_OFF",
    "ASHMEM_MMAP_OFF",
    "ASHMEM_OPEN_OFF",
    "ASHMEM_RELEASE_OFF",
    "ASHMEM_SHOW_FDINFO_OFF",
    "CONFIGFS_READ_ITER_OFF",
    "CONFIGFS_BIN_WRITE_ITER_OFF",
    "COPY_SPLICE_READ_OFF",
    "NOOP_LLSEEK_OFF",
    "SLIDE_NFULNL_LOGGER_NAME_OFF",
    "SLIDE_NFULNL_LOGGER_OBJECT_OFF",
    "SLIDE_RANDOM_TABLE_BOOT_ID_DATA_PTR_OFF",
    "SLIDE_SYSCTL_BOOTID_OFF",
    "SLIDE_TRACEFS_EVENT_ID",
    "SLIDE_TRACEFS_WORKER_CALLER_OFF",
)

# Measured, but optional by contract: the chain guards each of these with `#ifdef`, because a kernel
# that does not have the second return address still has the first. They are listed here so the macro
# diff does not report them as lost, and the header is compiled twice - once without them, to prove
# they really are optional, and once with them, to prove the code they enable still builds.
OPTIONAL_MEASURED = ("SLIDE_TRACEFS_VFORK_CALLER_OFF",)

DEFINE = re.compile(r"^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)", re.MULTILINE)

# The translation unit is a stub too: the header uses socket constants under `APP_PAYLOAD`, and it
# expects its includer to have the project's own headers in scope by the time it is reached (that is
# how `src/offset.h` gets it). Including the standard headers the chain's own TU would is enough.
TU = """\
#include <stdint.h>
#include <sys/socket.h>
#include <netinet/in.h>

#include "target.h"
"""


def stub_measured(measured: tuple[str, ...]) -> str:
    lines = [
        "/* Generated by tools/port/syntax_check.py: values are stubs, sizes do not matter. */",
        "#ifndef SYNTAX_CHECK_MEASURED_H",
        "#define SYNTAX_CHECK_MEASURED_H",
    ]
    for macro in measured:
        if macro == "BUILD_FINGERPRINT":
            lines.append(f'#define {macro} "syntax-check-stub"')
        elif macro == "SLIDE_TRACEFS_EVENT_ID":
            lines.append(f"#define {macro} 108")
        else:
            lines.append(f"#define {macro} 0x1000ULL")
    lines += ['#include "p0_fingerprint.h"', "#endif", ""]
    return "\n".join(lines)


STUB_FINGERPRINT = """\
/* Generated by tools/port/syntax_check.py; the shape of a generated P0 table, with stub words. */
#ifndef P0_FINGERPRINT_H
#define P0_FINGERPRINT_H

#define P0_FINGERPRINT_WORDS 8

static const uint16_t p0_fingerprint_offsets[P0_FINGERPRINT_WORDS] = {
  0x000, 0x200, 0x400, 0x600, 0x800, 0xa00, 0xc00, 0xe00,
};

struct p0_fingerprint {
  uintptr_t slide;
  uint64_t words[P0_FINGERPRINT_WORDS];
};

static const struct p0_fingerprint p0_fingerprints[] = {
  { 0x000000ULL, { 0ULL, 0ULL, 0ULL, 0ULL, 0ULL, 0ULL, 0ULL, 0ULL } },
};

#endif
"""


def defines(path: Path) -> set[str]:
    return set(DEFINE.findall(path.read_text(encoding="utf-8")))


def compiler() -> str:
    """The compiler to check with: the NDK's when it is configured, the host's otherwise.

    Syntax-only, so either one finds the same missing macro; using the NDK's first is a courtesy so a
    header that compiles here will also compile in the build that ships it.
    """
    ndk = os.environ.get("ANDROID_NDK_HOME")
    if ndk:
        for host in ("darwin-x86_64", "linux-x86_64"):
            candidate = Path(ndk) / "toolchains" / "llvm" / "prebuilt" / host / "bin" / "clang"
            if candidate.exists():
                return str(candidate)
    found = shutil.which("clang")
    if found:
        return found
    raise SystemExit("no clang: set ANDROID_NDK_HOME, or install clang")


def check(target: str, reference: str | None, keep: bool) -> int:
    source = TARGETS / target / "target.h"
    if not source.exists():
        raise SystemExit(f"no such target header: {source}")

    scratch = Path(tempfile.mkdtemp(prefix=f"syntax-{target}-"))
    try:
        shutil.copyfile(source, scratch / "target.h")
        (scratch / "p0_fingerprint.h").write_text(STUB_FINGERPRINT, encoding="utf-8")
        (scratch / "tu.c").write_text(TU, encoding="utf-8")

        # Four, because the two answers are different questions: without the optional measurements the
        # header must build for a kernel that lacks them, with them the code they enable must build,
        # and each of those has to hold for both the app payload and the standalone binary the Makefile
        # also produces. A port that only ever compiled one way would find out on the device.
        passes = (
            ("app payload, without the optional measurements", MEASURED, True),
            ("app payload, with the optional measurements", MEASURED + OPTIONAL_MEASURED, True),
            ("standalone binary, without the optional measurements", MEASURED, False),
            ("standalone binary, with the optional measurements", MEASURED + OPTIONAL_MEASURED, False),
        )
        for label, measured, app in passes:
            (scratch / "measured.h").write_text(stub_measured(measured), encoding="utf-8")
            command = [
                compiler(), "-fsyntax-only", "-std=gnu11",
                "-DSLIDE_STACK_WRITER=1",
                "-Werror=implicit-function-declaration", "-Werror=undef",
            ]
            if app:
                # Both spellings, since that is how the tree tests it (`src/offset.h` and `Makefile`).
                command += ["-DAPP_PAYLOAD=1"]
            command += ["-I", str(scratch), str(scratch / "tu.c")]
            result = subprocess.run(command, capture_output=True, text=True)
            print(f"{target}: {label}: {'ok' if result.returncode == 0 else 'FAILED'}")
            if result.returncode != 0:
                print(result.stderr, file=sys.stderr)
                return 1

        if reference:
            accounted = set(MEASURED) | set(OPTIONAL_MEASURED) | defines(source)
            missing = defines(TARGETS / reference / "target.h") - accounted
            if missing:
                print(f"{target}: these macros are in {reference} but nothing in this header defines "
                      "them or measures them:", file=sys.stderr)
                for macro in sorted(missing):
                    print(f"  - {macro}", file=sys.stderr)
                return 1
            print(f"{target}: every macro {reference} defines is defined or measured here")
        return 0
    finally:
        if keep:
            print(f"kept {scratch}")
        else:
            shutil.rmtree(scratch, ignore_errors=True)


def self_test() -> int:
    """Prove the check can fail: a header that uses an undefined macro must not pass."""
    scratch = Path(tempfile.mkdtemp(prefix="syntax-self-test-"))
    try:
        (scratch / "measured.h").write_text(stub_measured(MEASURED), encoding="utf-8")
        (scratch / "p0_fingerprint.h").write_text(STUB_FINGERPRINT, encoding="utf-8")
        (scratch / "tu.c").write_text(TU, encoding="utf-8")

        (scratch / "target.h").write_text(
            '#include "measured.h"\n#define SUM (INIT_TASK_OFF + COMMIT_CREDS_OFF)\n'
            "static unsigned long sum = SUM;\n", encoding="utf-8"
        )
        good = subprocess.run(
            [compiler(), "-fsyntax-only", "-std=gnu11", "-Wall", "-I", str(scratch),
             str(scratch / "tu.c")],
            capture_output=True, text=True,
        )
        # The failure this check exists to catch is a header that *uses* a name nothing measured, which
        # the compiler reports as an undeclared identifier - not `-Wundef`, which only fires in `#if`.
        (scratch / "target.h").write_text(
            '#include "measured.h"\nstatic unsigned long sum = NOT_MEASURED_ANYWHERE;\n',
            encoding="utf-8",
        )
        bad = subprocess.run(
            [compiler(), "-fsyntax-only", "-std=gnu11", "-I", str(scratch),
             str(scratch / "tu.c")],
            capture_output=True, text=True,
        )
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    results = [
        ("a header the stubs satisfy compiles", good.returncode == 0),
        ("an undefined macro fails the check", bad.returncode != 0),
        ("the stub header carries every measured macro",
         all(macro in stub_measured(MEASURED) for macro in MEASURED)),
    ]
    for label, passed in results:
        print(f"self-test: {label} {'ok' if passed else 'FAILED'}")
    if all(passed for _, passed in results):
        print("self-test: the check passes what compiles and fails what does not")
        return 0
    if good.returncode != 0:
        print(good.stderr, file=sys.stderr)
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--target", help="the target directory to check, e.g. dm2q-S916BXXUAGZIF")
    parser.add_argument("--reference", help="a target to diff macro names against")
    parser.add_argument("--keep", action="store_true", help="leave the scratch directory in place")
    parser.add_argument("--self-test", action="store_true", help="check the check")
    arguments = parser.parse_args()

    if arguments.self_test:
        return self_test()
    if not arguments.target:
        parser.error("--target is required")
    return check(arguments.target, arguments.reference, arguments.keep)


if __name__ == "__main__":
    sys.exit(main())
